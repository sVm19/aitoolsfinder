"""Request and response schemas for the grounded AI recommendations API (Phase 5)."""

import uuid
from datetime import datetime
from typing import Dict, List, Optional

from pydantic import BaseModel, ConfigDict, Field, field_validator

MAX_QUERY_LENGTH = 1000
MAX_CANDIDATES = 15
MATCH_SCORE_METHOD = "rank_relative_v1"
PRICING_MODELS = {
    "free",
    "freemium",
    "paid",
    "usage_based",
    "one_time",
    "contact_sales",
    "unknown",
}


class RecommendationRequest(BaseModel):
    """Natural-language request plus optional catalog constraints."""

    model_config = ConfigDict(extra="forbid")

    query: str = Field(
        min_length=1,
        max_length=MAX_QUERY_LENGTH,
        description="Natural language user request for tool recommendations",
    )
    category_slugs: Optional[List[str]] = Field(
        default=None,
        max_length=5,
        description="Optional category slug filter",
    )
    tag_slugs: Optional[List[str]] = Field(
        default=None,
        max_length=5,
        description="Optional tag slug filter",
    )
    pricing_model: Optional[str] = Field(
        default=None,
        description="Optional pricing model filter",
    )
    limit: int = Field(
        default=MAX_CANDIDATES,
        ge=1,
        le=MAX_CANDIDATES,
        description="Maximum number of catalog candidates to consider (1-15)",
    )

    @field_validator("query")
    @classmethod
    def normalize_query(cls, value: str) -> str:
        normalized = value.strip()
        if not normalized:
            raise ValueError("Query must not be blank.")
        return normalized

    @field_validator("pricing_model")
    @classmethod
    def validate_pricing_model(cls, value: Optional[str]) -> Optional[str]:
        if value is None:
            return None
        normalized = value.strip().lower()
        if normalized not in PRICING_MODELS:
            raise ValueError(f"Unsupported pricing model: {value}")
        return normalized

    @field_validator("category_slugs", "tag_slugs")
    @classmethod
    def normalize_slugs(cls, value: Optional[List[str]]) -> Optional[List[str]]:
        if value is None:
            return None
        cleaned = [slug.strip().lower() for slug in value if slug.strip()]
        return cleaned or None


class PricingPlanSummary(BaseModel):
    """Authoritative pricing copied from the catalog, never generated by the model."""

    name: str
    amount_minor: Optional[int] = None
    currency: Optional[str] = None
    billing_interval: str = "unknown"
    is_free: bool = False
    limitations: Dict[str, str] = Field(default_factory=dict)


class RecommendationItem(BaseModel):
    """A verified catalog tool with grounded explanation fields."""

    tool_id: str
    slug: str
    name: str
    tagline: Optional[str] = None
    match_score: float = Field(
        ge=0,
        le=100,
        description="Relative fit score within this result set (0-100)",
    )
    match_score_method: str = MATCH_SCORE_METHOD
    match_reasons: List[str]
    tradeoffs: List[str]
    relevant_feature_slugs: List[str]
    pricing: List[PricingPlanSummary]
    website_url: str
    is_verified: bool
    last_verified_at: Optional[datetime] = None


class RecommendationResponse(BaseModel):
    """Ranked recommendations plus transparency metadata."""

    items: List[RecommendationItem] = Field(default_factory=list)
    personalized: bool = False
    notice: Optional[str] = None
    prompt_version: str
    latency_ms: int


class FeedbackRequest(BaseModel):
    """Accuracy feedback for one recommended tool."""

    model_config = ConfigDict(extra="forbid")

    tool_id: uuid.UUID = Field(description="UUID of the recommended tool")
    query: Optional[str] = Field(
        default=None,
        max_length=MAX_QUERY_LENGTH,
        description="Original recommendation query, when available",
    )
    rating: int = Field(
        ge=1,
        le=5,
        description="Accuracy rating: 1=poor, 5=excellent",
    )
    comment: Optional[str] = Field(
        default=None,
        max_length=500,
        description="Optional free-text comment",
    )


class FeedbackResponse(BaseModel):
    """Stored feedback record."""

    id: str
    tool_id: str
    rating: int
    created_at: datetime